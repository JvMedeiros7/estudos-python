#Funções estão preços a uma palavra Rotina de execução de um bloco de código. Elas são definidas usando a palavra-chave def, seguida pelo nome da função e parênteses. As funções podem receber parâmetros e retornar valores. Aqui estão alguns exemplos de funções em Python:

# Definindo uma função simples

def saudacao(mensagem):
    print(f"Olá! {mensagem}")
# Chamando a função
saudacao("Tudo bom")  # Saída: Olá! Tudo bom

# Função com retorno de valor

def soma(a, b):
    return a + b
resultado = soma(5, 3)
print(resultado)  # Saída: 8


def mostrar_linha():
    print("-" * 30) 
mostrar_linha()  # Saída: ------------------------------

